    static async Task TcpPing(string host, int port, int timeoutMs)
    {
        using var client = new TcpClient();
        var sw = Stopwatch.StartNew();

        try
        {
            var connectTask = client.ConnectAsync(host, port);
            if (await Task.WhenAny(connectTask, Task.Delay(timeoutMs)) != connectTask)
            {
                Console.WriteLine($"[TIMEOUT] {host}:{port}");
                return;
            }

            sw.Stop();
            Console.WriteLine($"[OK] {host}:{port} - {sw.ElapsedMilliseconds} ms");
        }
        catch (SocketException ex)
        {
            Console.WriteLine($"[FAIL] {host}:{port} - {ex.SocketErrorCode}");
        }
        catch (Exception ex)
        {
            Console.WriteLine($"[ERROR] {host}:{port} - {ex.Message}");
        }
    }

